import type { ColorScheme, PresetId, ThemeColors, ThemeConfig } from "./types";

type BuiltInPresetId = Exclude<PresetId, "custom">;

function makeColors(
  partial: Partial<ThemeColors> & Pick<ThemeColors, "bg" | "text" | "accent">
): ThemeColors {
  return {
    bg2: partial.bg2 ?? partial.bg,
    panel: partial.panel ?? "rgba(30,30,30,0.85)",
    panel2: partial.panel2 ?? "rgba(40,40,40,0.9)",
    panelHover: partial.panelHover ?? "rgba(55,55,55,0.9)",
    textMuted: partial.textMuted ?? "#a1a1aa",
    textFaint: partial.textFaint ?? "#71717a",
    border: partial.border ?? "rgba(255,255,255,0.08)",
    accentFg: partial.accentFg ?? "#0a0a0a",
    inputBg: partial.inputBg ?? "rgba(0,0,0,0.35)",
    success: partial.success ?? "#34d399",
    warning: partial.warning ?? "#fbbf24",
    danger: partial.danger ?? "#f87171",
    nav: partial.nav ?? partial.bg,
    navText: partial.navText ?? partial.text,
    info: partial.info ?? partial.accent,
    focusRing: partial.focusRing ?? partial.accent,
    backdrop: partial.backdrop ?? "rgba(0,0,0,0.4)",
    ...partial,
  } as ThemeColors;
}

